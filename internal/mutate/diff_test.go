func gitRun(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v failed: %v\n%s", args, err, string(out))
	}
	return strings.TrimSpace(string(out))
}

func initGitRepo(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	gitRun(t, dir, "init", "-b", "main")
	gitRun(t, dir, "config", "user.name", "Test User")
	gitRun(t, dir, "config", "user.email", "test@example.com")
	for rel, body := range files {
		full := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	gitRun(t, dir, "add", ".")
	gitRun(t, dir, "commit", "-m", "initial")
	return dir
}

func TestComputeDiffShallowAndMissingBaseFailClosed(t *testing.T) {
	ctx := context.Background()
	b := gobuild.Build{GOOS: "darwin", GOARCH: "arm64", CGOEnabled: true}

	origin := initGitRepo(t, map[string]string{
		"go.mod": "module example.com/p\n\ngo 1.26\n",
		"p.go":   "package p\nfunc F(a int) bool { return a < 1 }\n",
	})
	gitRun(t, origin, "checkout", "-b", "feat")
	if err := os.WriteFile(filepath.Join(origin, "p.go"), []byte("package p\nfunc F(a int) bool { return a < 2 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	gitRun(t, origin, "commit", "-am", "feat edit")

	shallow := filepath.Join(t.TempDir(), "shallow")
	gitRun(t, t.TempDir(), "clone", "--depth=1", "file://"+origin, shallow)
	if _, err := ComputeDiff(ctx, gate.OS{}, shallow, "main", b); err == nil || !strings.Contains(err.Error(), "fetch-depth: 0") {
		t.Fatalf("shallow error = %v, want fetch-depth: 0 hint", err)
	}

	// Unrelated orphan branch with no merge base.
	orphan := initGitRepo(t, map[string]string{
		"go.mod": "module example.com/p\n\ngo 1.26\n",
		"p.go":   "package p\nfunc F(a int) bool { return a < 1 }\n",
	})
	gitRun(t, orphan, "checkout", "--orphan", "side")
	if err := os.WriteFile(filepath.Join(orphan, "p.go"), []byte("package p\nfunc F(a int) bool { return a < 3 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	gitRun(t, orphan, "add", ".")
	gitRun(t, orphan, "commit", "-m", "orphan commit")
	if _, err := ComputeDiff(ctx, gate.OS{}, orphan, "main", b); err == nil || !strings.Contains(err.Error(), "fetch-depth: 0") {
		t.Fatalf("orphan error = %v, want fetch-depth: 0 hint", err)
	}
}

func TestComputeDiffScopeExclusionsAndVacuousCases(t *testing.T) {
	ctx := context.Background()
	b := gobuild.Build{GOOS: "darwin", GOARCH: "arm64", CGOEnabled: true}

	dir := initGitRepo(t, map[string]string{
		"go.mod":        "module example.com/p\n\ngo 1.26\n",
		"p.go":          "package p\nfunc F(a int) bool { return a < 1 }\n",
		"p_test.go":     "package p\nimport \"testing\"\nfunc TestF(t *testing.T) {}\n",
		"README.md":     "# hi\n",
		"testdata/f.go": "package p\nfunc G(a int) bool { return a < 1 }\n",
		"gen.go":        "// Code generated by tool. DO NOT EDIT.\npackage p\nfunc Gen(a int) bool { return a < 1 }\n",
		"old.go":        "package p\nfunc Renamed(a int) bool { return a < 1 }\n",
	})
	gitRun(t, dir, "checkout", "-b", "feat")

	// Case 1: test-only + non-go + testdata + generated + pure rename => zero production lines (vacuous).
	if err := os.WriteFile(filepath.Join(dir, "p_test.go"), []byte("package p\nimport \"testing\"\nfunc TestF(t *testing.T) { _ = 1 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "README.md"), []byte("# updated\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "testdata/f.go"), []byte("package p\nfunc G(a int) bool { return a < 2 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "gen.go"), []byte("// Code generated by tool. DO NOT EDIT.\npackage p\nfunc Gen(a int) bool { return a < 2 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	gitRun(t, dir, "mv", "old.go", "renamed.go")
	gitRun(t, dir, "commit", "-am", "non-prod changes and pure rename")

	res, err := ComputeDiff(ctx, gate.OS{}, dir, "main", b)
	if err != nil {
		t.Fatal(err)
	}
	if res.HasChangedProdLines() {
		t.Fatalf("expected HasChangedProdLines=false, got %+v", res.ProductionFiles)
	}

	// Case 2: comment-only edit on prod file => HasChangedProdLines=true (so layer runs and returns 0 mutants pass).
	if err := os.WriteFile(filepath.Join(dir, "p.go"), []byte("package p\n// just a comment\nfunc F(a int) bool { return a < 1 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	resComment, err := ComputeDiff(ctx, gate.OS{}, dir, "main", b)
	if err != nil {
		t.Fatal(err)
	}
	if !resComment.HasChangedProdLines() || !resComment.InBuildFiles["p.go"][2] {
		t.Fatalf("expected comment line in p.go in build files, got %+v", resComment.InBuildFiles)
	}

	// Case 3: dirty working tree + untracked file + out-of-build _linux.go on darwin.
	if err := os.WriteFile(filepath.Join(dir, "new_untracked.go"), []byte("package p\nfunc U(a int) bool { return a < 3 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "plat_linux.go"), []byte("package p\nfunc Lin(a int) bool { return a < 4 }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	resMixed, err := ComputeDiff(ctx, gate.OS{}, dir, "main", b)
	if err != nil {
		t.Fatal(err)
	}
	if len(resMixed.InBuildFiles["new_untracked.go"]) != 2 {
		t.Fatalf("expected untracked file lines, got %+v", resMixed.InBuildFiles)
	}
	if len(resMixed.OutOfBuildFiles["plat_linux.go"]) != 2 {
		t.Fatalf("expected _linux.go in OutOfBuildFiles, got %+v", resMixed.OutOfBuildFiles)
	}
	// O2: .go-tops/mutation.diff must contain only filtered prod files + untracked prod files.
	mutDiffBytes, err := os.ReadFile(resMixed.DiffPath)
	if err != nil {
		t.Fatal(err)
	}
	mutDiff := string(mutDiffBytes)
	for _, forbidden := range []string{"p_test.go", "README.md", "testdata/f.go", "gen.go"} {
		if strings.Contains(mutDiff, forbidden) {
			t.Fatalf("filtered mutation.diff leaked excluded path %q:\n%s", forbidden, mutDiff)
		}
	}
	for _, wanted := range []string{"+++ b/p.go", "+++ b/new_untracked.go"} {
		if !strings.Contains(mutDiff, wanted) {
			t.Fatalf("filtered mutation.diff missing %q:\n%s", wanted, mutDiff)
		}
	}

	// B3: hostile repo git diff configs must not break diff parsing or widen hunks.
	gitRun(t, dir, "config", "diff.mnemonicPrefix", "true")
	gitRun(t, dir, "config", "diff.noprefix", "true")
	gitRun(t, dir, "config", "diff.srcPrefix", "src/")
	gitRun(t, dir, "config", "diff.dstPrefix", "dst/")
	gitRun(t, dir, "config", "diff.interHunkContext", "10")
	resHostile, err := ComputeDiff(ctx, gate.OS{}, dir, "main", b)
	if err != nil {
		t.Fatal(err)
	}
	if !resHostile.InBuildFiles["p.go"][2] || resHostile.InBuildFiles["p.go"][3] {
		t.Fatalf("hostile git config corrupted InBuildFiles[p.go]: %+v", resHostile.InBuildFiles["p.go"])
	}
}

func TestComputeDiffSubdirectoryModule(t *testing.T) {
	ctx := context.Background()
	b := gobuild.Build{GOOS: "darwin", GOARCH: "arm64", CGOEnabled: true}

	root := initGitRepo(t, map[string]string{
		"README.md":       "root\n",
		"sub/mod/go.mod":  "module example.com/sub\n\ngo 1.26\n",
		"sub/mod/calc.go": "package mod\nfunc Lt(a, b int) bool { return a < b }\n",
	})
	gitRun(t, root, "checkout", "-b", "feat")
	if err := os.WriteFile(filepath.Join(root, "sub/mod/calc.go"), []byte("package mod\nfunc Lt(a, b int) bool { return a <= b }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	gitRun(t, root, "commit", "-am", "edit submod")

	subDir := filepath.Join(root, "sub/mod")
	res, err := ComputeDiff(ctx, gate.OS{}, subDir, "main", b)
	if err != nil {
		t.Fatal(err)
	}
	if res.ModPrefix != "sub/mod" {
		t.Fatalf("ModPrefix = %q, want sub/mod", res.ModPrefix)
	}
	if !res.InBuildFiles["calc.go"][2] {
		t.Fatalf("expected module-relative calc.go:2 in InBuildFiles, got %+v", res.InBuildFiles)
	}
}
